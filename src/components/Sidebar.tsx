export function Sidebar() {
  const pathname = usePathname();
  const settings = useStore((s) => s.settings);
  const teamSectionLabel = settings?.teamSectionLabel ?? "Team";
  const myTasksLabel = settings?.myTasksLabel ?? "My Tasks";
  const logoUrl = settings?.business?.logoUrl;
  const companyName = settings?.business?.name || "Invoice";
  const [mobileOpen, setMobileOpen] = useState(false);
  const [theme, setTheme] = useState<"light" | "dark">("dark");
  
  // Collapsible sections state - store in localStorage
  const [expandedSections, setExpandedSections] = useState<Record<string, boolean>>(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("sidebar-expanded-sections");
      if (saved) {
        try {
          return JSON.parse(saved);
        } catch {
          return {
            "overview": true,
            "client-management": true,
            "invoicing": true,
            "team": true,
            "system": false,
          };
        }
      }
    }
    return {
      "overview": true,
      "client-management": true,
      "invoicing": true,
      "team": true,
      "system": false,
    };
  });

  // Save expanded sections to localStorage
  useEffect(() => {
    localStorage.setItem("sidebar-expanded-sections", JSON.stringify(expandedSections));
  }, [expandedSections]);

  // Load theme from localStorage on mount
  useEffect(() => {
    const savedTheme = localStorage.getItem("theme") as "light" | "dark" | null;
    if (savedTheme) {
      setTheme(savedTheme);
      document.documentElement.classList.toggle("dark", savedTheme === "dark");
    } else {
      // Check system preference
      const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
      const initialTheme = prefersDark ? "dark" : "light";
      setTheme(initialTheme);
      document.documentElement.classList.toggle("dark", prefersDark);
    }
  }, []);

  // Toggle theme
  const toggleTheme = () => {
    const newTheme = theme === "dark" ? "light" : "dark";
    setTheme(newTheme);
    localStorage.setItem("theme", newTheme);
    document.documentElement.classList.toggle("dark", newTheme === "dark");
  };

  // Close mobile menu on route change
  useEffect(() => {
    setMobileOpen(false);
  }, [pathname]);

  // Close mobile menu on escape key
  useEffect(() => {
    const handleEscape = (e: KeyboardEvent) => {
      if (e.key === "Escape") setMobileOpen(false);
    };
    window.addEventListener("keydown", handleEscape);
    return () => window.removeEventListener("keydown", handleEscape);
  }, []);

  const toggleSection = (sectionId: string) => {
    setExpandedSections(prev => ({
      ...prev,
      [sectionId]: !prev[sectionId]
    }));
  };

  const isItemActive = (href: string) => {
    return pathname === href || (href !== "/dashboard" && pathname.startsWith(href + "/"));
  };

  return (
    <>
    {/* Mobile menu button */}
    <button
      onClick={() => setMobileOpen(!mobileOpen)}
      className="fixed left-4 top-4 z-50 flex h-11 w-11 items-center justify-center rounded-lg border border-neutral-200 bg-white text-neutral-900 lg:hidden dark:border-neutral-800 dark:bg-neutral-900 dark:text-white"
      aria-label={mobileOpen ? "Close menu" : "Open menu"}
    >
      {mobileOpen ? (
        <svg className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
          <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
        </svg>
      ) : (
        <svg className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
          <path strokeLinecap="round" strokeLinejoin="round" d="M4 6h16M4 12h16M4 18h16" />
        </svg>
      )}
    </button>

    {/* Mobile backdrop */}
    {mobileOpen && (
      <div
        className="fixed inset-0 z-[60] bg-black/50 lg:hidden"
        onClick={() => setMobileOpen(false)}
      />
    )}

    {/* Sidebar */}
    <aside
      className={`fixed left-0 top-0 z-[70] flex h-full w-64 flex-col border-r border-neutral-200 bg-white transition-transform duration-300 lg:translate-x-0 dark:border-neutral-800 dark:bg-neutral-950 ${
        mobileOpen ? "translate-x-0" : "-translate-x-full"
      }`}
    >
      {/* Logo */}
      <div className="flex h-16 items-center gap-3 border-b border-neutral-200 px-4 dark:border-neutral-800">
        {logoUrl ? (
          <img src={logoUrl} alt={companyName} className="h-8 w-8 rounded object-contain" />
        ) : (
          <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded bg-orange-500 text-sm font-bold text-white">
            {companyName.charAt(0).toUpperCase()}
          </div>
        )}
        <span className="text-lg font-semibold text-neutral-900 dark:text-white">
          {companyName}
        </span>
      </div>

      {/* Navigation */}
      <nav className="flex-1 space-y-1 overflow-y-auto p-3">
        {navSections.map((section) => {
          const isExpanded = expandedSections[section.id] ?? true;
          const hasActiveItem = section.items.some(item => isItemActive(item.href));
          
          return (
            <div key={section.id} className="mb-1">
              {section.id === "overview" ? (
                // Dashboard is standalone, no collapsible section
                section.items.map((item) => {
                  const active = isItemActive(item.href);
                  return (
                    <Link
                      key={item.href}
                      href={item.href}
                      className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
                        active
                          ? "bg-orange-100 text-orange-600 dark:bg-orange-950/50 dark:text-orange-400"
                          : "text-neutral-600 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800 dark:hover:text-white"
                      }`}
                    >
                      <item.icon className="h-5 w-5 shrink-0" />
                      {item.label}
                    </Link>
                  );
                })
              ) : (
                <>
                  {/* Section Header */}
                  <button
                    onClick={() => toggleSection(section.id)}
                    className={`flex w-full items-center gap-2 rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
                      hasActiveItem
                        ? "text-orange-600 dark:text-orange-400"
                        : "text-neutral-700 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-300 dark:hover:bg-neutral-800 dark:hover:text-white"
                    }`}
                  >
                    <ChevronIcon className="h-4 w-4 shrink-0" isOpen={isExpanded} />
                    {section.icon && <section.icon className="h-5 w-5 shrink-0" />}
                    <span className="flex-1 text-left">{section.id === "team" ? teamSectionLabel : section.label}</span>
                  </button>

                  {/* Section Items */}
                  {isExpanded && (
                    <div className="ml-6 mt-1 space-y-0.5">
                      {section.items.map((item) => {
                        const active = isItemActive(item.href);
                        const label = item.href === "/dashboard/my-tasks" ? myTasksLabel : item.label;
                        
                        return (
                          <Link
                            key={item.href}
                            href={item.href}
                            className={`flex items-center gap-3 rounded-lg px-3 py-2 text-sm transition-colors ${
                              active
                                ? "bg-orange-100 text-orange-600 dark:bg-orange-950/50 dark:text-orange-400"
                                : "text-neutral-600 hover:bg-neutral-50 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800/50 dark:hover:text-white"
                            }`}
                          >
                            <item.icon className="h-4 w-4 shrink-0" />
                            {label}
                          </Link>
                        );
                      })}
                    </div>
                  )}
                </>
              )}
            </div>
          );
        })}
      </nav>

      {/* Footer */}
      <div className="border-t border-neutral-200 dark:border-neutral-800 p-3 space-y-1">
        {/* AI Assistant - Hidden for now, keeping code for future use
        <button
          type="button"
          onClick={() => window.dispatchEvent(new CustomEvent("open-ai-chat"))}
          className="flex w-full items-center gap-3 rounded-lg px-3 py-3 md:py-2 text-sm font-medium text-neutral-600 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800 dark:hover:text-white cursor-pointer"
        >
          <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-orange-100 text-orange-600 dark:bg-orange-500/20 dark:text-orange-400">
            <svg className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M8 10h.01M12 10h.01M16 10h.01M9 16H5a2 2 0 01-2-2V6a2 2 0 012-2h14a2 2 0 012 2v8a2 2 0 01-2 2h-5l-5 5v-5z" /></svg>
          </span>
          <span>AI Invoice Assistant</span>
          <span className="ml-auto text-xs text-neutral-400 dark:text-neutral-500">⌘K</span>
        </button>
        */}
        <div className="flex items-center gap-1">
          <button
            type="button"
            onClick={toggleTheme}
            className="flex h-11 w-11 md:h-10 md:w-10 shrink-0 items-center justify-center rounded-lg transition-colors cursor-pointer text-neutral-600 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800 dark:hover:text-white"
            title={theme === "dark" ? "Switch to light mode" : "Switch to dark mode"}
            aria-label={theme === "dark" ? "Switch to light mode" : "Switch to dark mode"}
          >
            {theme === "dark" ? (
              <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M12 3v2.25m6.364.386l-1.591 1.591M21 12h-2.25m-.386 6.364l-1.591-1.591M12 18.75V21m-4.773-4.227l-1.591 1.591M5.25 12H3m4.227-4.773L5.636 5.636M15.75 12a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0z" />
              </svg>
            ) : (
              <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M21.752 15.002A9.718 9.718 0 0118 15.75c-5.385 0-9.75-4.365-9.75-9.75 0-1.33.266-2.597.748-3.752A9.753 9.753 0 003 11.25C3 16.635 7.365 21 12.75 21a9.753 9.753 0 009.002-5.998z" />
              </svg>
            )}
          </button>
          <Link
            href="/dashboard/settings"
            className={`flex h-11 w-11 md:h-10 md:w-10 shrink-0 items-center justify-center rounded-lg transition-colors cursor-pointer ${
              pathname === "/dashboard/settings" || pathname.startsWith("/dashboard/settings/")
                ? "bg-orange-100 text-orange-600 dark:bg-orange-950/50 dark:text-orange-400"
                : "text-neutral-600 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800 dark:hover:text-white"
            }`}
            title="Settings"
            aria-label="Settings"
          >
            <SettingsIcon className="h-5 w-5" />
          </Link>
          <Link
            href="/dashboard/account"
            className={`flex flex-1 items-center gap-3 rounded-lg px-3 py-3 md:py-2.5 text-sm font-medium transition-colors cursor-pointer ${
              pathname === "/dashboard/account" || pathname.startsWith("/dashboard/account/")
                ? "bg-orange-100 text-orange-600 dark:bg-orange-950/50 dark:text-orange-400"
                : "text-neutral-600 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800 dark:hover:text-white"
            }`}
          >
            <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-neutral-200 text-neutral-700 dark:bg-neutral-700 dark:text-white text-sm font-medium">
              U
            </span>
            <span>User profile</span>
          </Link>
        </div>
      </div>
    </aside>
    </>
  );
}
